public class Points
{
    public int x;
    public int y;

    /// <summary>
    /// конструктор для реализации полей - координат шахматной доски 
    /// </summary>
    /// <param name="x">координата икс</param>
    /// <param name="y">координата игрек</param>
    public Points(int x, int y)
    {
        this.x = x;
        this.y = y;
    }
}